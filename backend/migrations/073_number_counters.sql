-- 073 (D-210): счётчики номеров обращений (СО), нарядов (НР) и табельных номеров «Персонала» (П).
-- Раньше номер считался как «наибольший существующий + 1»: при одновременном создании второй запрос получал ошибку уникальности.
-- Счётчик продолжает существующую нумерацию (при первом обращении берёт наибольший существующий номер).
BEGIN;
CREATE TABLE IF NOT EXISTS number_counters (
    key VARCHAR(32) NOT NULL,
    year INTEGER NOT NULL,
    seq INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (key, year)
);
COMMIT;
