def parse_clauses(path: str) -> list[Clause]:
    """Пункты договора: нумерованные абзацы (1., 1.1., 4.2.3) из тела и таблиц; ненумерованные абзацы прикрепляются к предыдущему пункту."""
    from .docx_fill import _iter_paragraphs
    doc = Document(path)
    out: list[Clause] = []
    section = ""
    last: Optional[Clause] = None
    for i, p in enumerate(_iter_paragraphs(doc)):
        t = (p.text or "").strip()
        if not t:
            continue
        m = CLAUSE_RE.match(t)
        if m and len(m.group(2)) > 2:
            no, body = m.group(1), m.group(2).strip()
            if "." not in no and len(body) < 80 and body.upper() == body or (no.count(".") == 0 and len(body) < 60):
                section = f"{no}. {body}"            # заголовок раздела («4. ПОРЯДОК ОПЛАТЫ»)
                last = None
                continue
            last = Clause(no=no, text=body, index=i, section=section)
            out.append(last)
        elif last is not None and len(t) > 20 and not t.isupper():
            last.text = f"{last.text} {t}"
        elif t.isupper() and len(t) < 80:
            section = t
            last = None
    return out


def _fill(our: str, ctx: dict) -> str:
    """Подстановка данных сделки в предлагаемую редакцию: {{delivery_days}}, {{warranty_hours}}, {{seller.signatory}} …"""
    def rep(m):
        key = m.group(1)
        cur: Any = ctx
        for part in key.split("."):
            cur = cur.get(part) if isinstance(cur, dict) else None
            if cur is None:
                break
        return str(cur) if cur not in (None, "") else "____"
    return re.sub(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}", rep, our)


def analyze(clauses: list[Clause], ctx: dict) -> list[Finding]:
    """Проверка пунктов по правилам продавца. ctx — данные сделки для подстановки в редакции (delivery_days, warranty_hours, seller.*)."""
    findings: list[Finding] = []
    for r in RULES:
        topic = re.compile(r["topic"], re.I)
        hits = [c for c in clauses if topic.search(c.text)]                      # тема — по тексту пункта
        if not hits and r.get("missing"):
            hits = [c for c in clauses if topic.search(c.section)]                # для «положение отсутствует» учитываем и заголовок раздела
        matched = False
        for c in hits:
            bad = re.compile(r["bad"], re.I) if r.get("bad") else None
            if bad is None:
                continue
            m = bad.search(c.text)
            if not m:
                continue
            # числовые пороги: срок приёмки, гарантия, ставка неустойки
            if r.get("threshold_days") and m.groups() and m.group(1).isdigit() and int(m.group(1)) <= r["threshold_days"]:
                continue
            if r.get("max_months") and m.groups() and m.group(1).isdigit() and int(m.group(1)) <= r["max_months"]:
                continue
            if r.get("max_daily_pct") and m.groups():
                try:
                    if float(m.group(1).replace(",", ".")) <= r["max_daily_pct"] and re.search(r"не более|но не свыше|ограничен", c.text, re.I):
                        continue
                except ValueError:
                    pass
            matched = True
            findings.append(Finding(rule=r["code"], group=r["group"], severity=r["severity"], clause=c.no, client_text=c.text[:1200], our_text=_fill(r["our"], ctx),
                                    comment="", risk=r["risk"], rationale=r["rationale"]))
        if not hits and r.get("missing"):
            findings.append(Finding(rule=r["code"], group=r["group"], severity=r["severity"], clause="новый пункт", client_text="(положение в договоре отсутствует)", our_text=_fill(r["our"], ctx),
                                    comment=f"Дополнить договор: {GROUPS[r['group']].lower()}", risk=r["risk"], rationale=r["rationale"]))
        elif hits and r.get("missing") and not matched and r.get("bad") is None:
            pass
    # порядок: по номеру пункта, критические первыми внутри одного пункта
    order = {"critical": 0, "major": 1, "minor": 2}
    findings.sort(key=lambda f: (f.clause == "новый пункт", [int(x) for x in f.clause.split(".")] if f.clause != "новый пункт" else [999], order[f.severity]))
    return findings


