"""Браузер: «Сделки» — крупные вкладки слева; заведение заявки на запчасти (каталог, файл, вставка, наличие по складам); удаление ошибочной заявки;
новый поставщик из выпадающего списка."""
import os
from playwright.sync_api import sync_playwright, expect
U="http://127.0.0.1:5173"; S="shots/"; issues=[]
with sync_playwright() as pw:
    b=pw.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx=b.new_context(viewport={"width":1440,"height":1000}, locale="ru-RU", timezone_id="Europe/Moscow")
    assert ctx.request.get(U+"/api/auth/me", headers={"X-Dev-User": "manager@example.com"}).ok
    m=ctx.new_page()
    m.on("console", lambda x: x.type=="error" and issues.append(f"console: {x.text[:200]}"))
    m.on("response", lambda r: (r.status>=400 and "/api/" in r.url and not r.url.endswith("/api/auth/me")) and issues.append(f"{r.status} {r.request.method} {r.url}"))
    m.on("pageerror", lambda e: issues.append(f"pageerror: {e}"))
    m.on("dialog", lambda d: d.accept())
    m.goto(U+"/deals"); m.locator(".deals-kind", has_text="Запасные части").wait_for()
    m.screenshot(path=S+"e01_deals_kinds.png")
    m.locator(".deals-kind", has_text="Запасные части").click()
    m.get_by_role("button", name="Новая заявка на запчасти").click()
    m.get_by_text("1. Клиент и машина").wait_for()
    m.get_by_label("Клиент *").select_option(index=1)
    m.get_by_placeholder("🔍 каталожный номер").fill("1R-07")
    m.get_by_role("row", name="1R-0750").get_by_role("button", name="добавить").click()
    m.get_by_text("Добавлено: 1R-0750").wait_for()
    m.get_by_role("button", name="Из файла заказа клиента").click()
    m.locator("input[type=file]").set_input_files(os.path.abspath("order.xlsx"))
    m.get_by_text("Из файла «order.xlsx»: строк 2").wait_for()
    m.get_by_role("button", name="Вставить из письма / Excel").click()
    m.locator("textarea").fill("4N-9618\tПалец\t3")
    m.get_by_role("button", name="Разобрать и добавить").click(); m.get_by_text("Разобрано строк: 1").wait_for()
    expect(m.get_by_text("Котельниково: 6")).to_be_visible(); expect(m.get_by_text("Куркино: 10")).to_be_visible()
    expect(m.get_by_text("есть 1 из 4")).to_be_visible(); expect(m.get_by_text("нет в каталоге")).to_be_visible()
    m.screenshot(path=S+"e02_create_form.png", full_page=True)
    m.get_by_role("button", name="3. Создать заявку (4 строки)").click()
    m.get_by_text("Запросы поставщикам").wait_for()
    sel=m.get_by_label("Поставщик для запроса"); sel.select_option(value="__new")
    m.get_by_placeholder("Название *").fill("Ningbo Hydraulic Parts"); m.get_by_role("button", name="Завести").click()
    m.get_by_text("Поставщик «Ningbo Hydraulic Parts» заведён").wait_for()
    m.screenshot(path=S+"e03_request_card.png", full_page=True)
    m.get_by_role("button", name="Удалить заявку").click()
    m.locator(".deals-kind.active", has_text="Запасные части").wait_for()
    b.close()
print("ISSUES:", issues or "none")
